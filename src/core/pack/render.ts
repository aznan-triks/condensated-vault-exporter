export interface PartAssemblyOptions {
	format: ExportFormat;
	header: string;
	footer: string;
	divider: string;
	partIndex: number;
	partTotal: number;
	/** 1-based volume this part belongs to (only used when there is > 1). */
	volumeIndex?: number;
	volumeTotal?: number;
	variables: Record<string, string>;
	title: string;
	stats: PlanStats;
	generatedAt: Date;
	citationIds: boolean;
	includeManifest: boolean;
	profile: { id: string; name: string };
	includeNoteSeparators: boolean;
}

/** Wraps the concatenated units of one part into a complete document. */
export function assemblePart(units: PackUnit[], options: PartAssemblyOptions): string {
	const variables: Record<string, string> = {
		...options.variables,
		part: String(options.partIndex + 1),
		total: String(options.partTotal),
		part_index: String(options.partIndex),
		volume: String(options.volumeIndex ?? 1),
		volume_total: String(options.volumeTotal ?? 1),
	};
	const volume =
		options.volumeTotal !== undefined && options.volumeTotal > 1
			? { index: options.volumeIndex ?? 1, total: options.volumeTotal }
			: undefined;
	const header = appendPartNotice(
		applyTemplate(options.header, variables).trim(),
		options.partIndex,
		options.partTotal,
		options.format,
		variables.title,
		volume,
	);
	const footer = options.footer.trim() === "" ? "" : applyTemplate(options.footer, variables).trim();

	switch (options.format) {
		case "json": {
			const documents = units
				.filter((unit) => unit.role !== "preamble" && unit.role !== "footer")
				.map((unit) => {
					try {
						return JSON.parse(unit.content) as unknown;
					} catch {
						return { content: unit.content };
					}
				});
			const payload: Record<string, unknown> = {
				bundle: {
					title: variables.title,
					profile: options.profile.name,
					profileId: options.profile.id,
					format: "json",
					generatedAt: options.generatedAt.toISOString(),
					part: options.partIndex + 1,
					parts: options.partTotal,
					notes: options.stats.kept,
					words: options.stats.words,
					tokens: options.stats.tokens,
					preamble: units.filter((unit) => unit.role === "preamble").map((unit) => unit.content).join("\n\n") || undefined,
					footer: units.filter((unit) => unit.role === "footer").map((unit) => unit.content).join("\n\n") || undefined,
				},
				documents,
			};
			return JSON.stringify(payload, null, 2);
		}
		case "jsonl": {
			const lines: string[] = [];
			lines.push(
				JSON.stringify({
					type: "bundle",
					title: variables.title,
					profile: options.profile.name,
					profileId: options.profile.id,
					generatedAt: options.generatedAt.toISOString(),
					part: options.partIndex + 1,
					parts: options.partTotal,
					notes: options.stats.kept,
					words: options.stats.words,
					tokens: options.stats.tokens,
					header: header || undefined,
				}),
			);
			for (const unit of units) {
				if (unit.role === "preamble") {
					lines.push(JSON.stringify({ type: "preamble", text: unit.content }));
					continue;
				}
				if (unit.role === "footer") {
					lines.push(JSON.stringify({ type: "footer", text: unit.content }));
					continue;
				}
				lines.push(unit.content);
			}
			if (footer && !units.some((unit) => unit.role === "footer")) lines.push(JSON.stringify({ type: "footer", text: footer }));
			return lines.join("\n");
		}
		case "xml": {
			const documents = units.filter((unit) => unit.role !== "preamble" && unit.role !== "footer").map((unit) => unit.content);
			const preambleUnits = units.filter((unit) => unit.role === "preamble").map((unit) => unit.content).join("\n\n");
			const prologue = `<?xml version="1.0" encoding="UTF-8"?>\n<bundle title="${escapeXml(variables.title)}" profile="${escapeXml(
				options.profile.name,
			)}" generatedAt="${options.generatedAt.toISOString()}" part="${options.partIndex + 1}" parts="${options.partTotal}" notes="${
				options.stats.kept
			}" words="${options.stats.words}" tokens="${options.stats.tokens}">`;
			const preamble = [header, preambleUnits].filter((part) => part.trim() !== "").join("\n\n");
			const headerXml = preamble ? `\n  <preamble><![CDATA[${preamble.replace(/]]>/g, "]]]]><![CDATA[>")}]]></preamble>` : "";
			const footerXml = footer ? `\n  <postamble><![CDATA[${footer.replace(/]]>/g, "]]]]><![CDATA[>")}]]></postamble>` : "";
			return `${prologue}${headerXml}\n${documents.join("\n")}${footerXml}\n</bundle>`;
		}
		default: {
			const separator = options.includeNoteSeparators ? options.divider : "\n\n";
			const body = units
				.filter((unit) => unit.role !== "footer")
				.map((unit) => unit.content.trimEnd());
			// One blank line around the divider: joining the pieces with "\n\n"
			// *and* inserting a separator between them produced three.
			const chunks = [header, body.join(`\n\n${separator.trim()}\n\n`)];
			if (footer) chunks.push(footer);
			const text = chunks.filter((chunk) => chunk.trim() !== "").join("\n\n");
			return text.replace(/\n{4,}/g, "\n\n\n");
		}
	}
}

function appendPartNotice(
	header: string,
	index: number,
	total: number,
	format: ExportFormat,
	title: string,
	volume?: { index: number; total: number },
): string {
	if (total <= 1 && !volume) return header;
	const notice = [
		total > 1 ? `Part ${index + 1} of ${total}` : null,
		volume ? `volume ${volume.index} of ${volume.total}` : null,
	]
		.filter(Boolean)
		.join(" · ");
	switch (format) {
		case "markdown":
			return `${header}\n\n> 📦 **${notice}** — “${title}”`;
		case "plain":
			return `${header}\n${notice}`;
		default:
			return header;
	}
}

