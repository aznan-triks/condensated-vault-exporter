/** Creates a fresh copy of a built-in profile (never shares mutable state). */
export function createBuiltinProfile(id: string): ExportProfile | undefined {
	const recipe = BUILTIN_PROFILES.find((entry) => entry.id === id);
	return recipe ? cloneProfile(recipe.build()) : undefined;
}

export function createDefaultProfiles(): ExportProfile[] {
	return BUILTIN_PROFILES.map((recipe) => cloneProfile(recipe.build()));
}

export function cloneProfile(profile: ExportProfile): ExportProfile {
	return deepClone(profile);
}

export function deepClone<T>(value: T): T {
	if (Array.isArray(value)) return value.map((item) => deepClone(item)) as unknown as T;
	if (value && typeof value === "object") {
		const out: Record<string, unknown> = {};
		for (const [key, entry] of Object.entries(value as Record<string, unknown>)) out[key] = deepClone(entry);
		return out as T;
	}
	return value;
}

/** Merges a stored (possibly older) profile with the current defaults. */
export function normalizeProfile(raw: Partial<ExportProfile>): ExportProfile {
	const fallbackName = raw.name ?? "Custom";
	const base =
		createBuiltinProfile(raw.id ?? "") ?? baseProfile({ id: raw.id ?? "custom", name: fallbackName, description: "" });
	const merged: ExportProfile = {
		...base,
		...raw,
		id: raw.id ?? base.id,
		name: raw.name ?? base.name,
		description: raw.description ?? base.description,
		targets: raw.targets ?? base.targets,
		include: raw.include ?? base.include,
		exclude: raw.exclude ?? base.exclude,
		filters: { ...base.filters, ...(raw.filters ?? {}) },
		order: { ...base.order, ...(raw.order ?? {}) },
		transform: { ...base.transform, ...(raw.transform ?? {}) },
		condensation: {
			...base.condensation,
			...(raw.condensation ?? {}),
			dedupe: { ...base.condensation.dedupe, ...(raw.condensation?.dedupe ?? {}) },
			boilerplate: { ...base.condensation.boilerplate, ...(raw.condensation?.boilerplate ?? {}) },
			summarize: { ...base.condensation.summarize, ...(raw.condensation?.summarize ?? {}) },
			dropStubs: { ...base.condensation.dropStubs, ...(raw.condensation?.dropStubs ?? {}) },
		},
		packaging: {
			...base.packaging,
			...(raw.packaging ?? {}),
			chunking: { ...base.packaging.chunking, ...(raw.packaging?.chunking ?? {}) },
		},
		output: { ...base.output, ...(raw.output ?? {}) },
		limits: { ...base.limits, ...(raw.limits ?? {}) },
	};
	delete (merged.transform as { tasks?: unknown }).tasks;
	return merged;
}

/** A one-line summary of a profile, shown in the profile list. */
export function describeProfile(profile: ExportProfile): string {
	const targets = profile.targets.length === 0 ? "the whole vault" : profile.targets.join(", ");
	const parts: string[] = [targets];
	switch (profile.packaging.chunking.mode) {
		case "single":
			parts.push("1 file");
			break;
		case "perNote":
			parts.push("1 file/note");
			break;
		case "perFolder":
			parts.push("1 file/folder");
			break;
		case "maxWords":
			parts.push(`≤${Math.round(profile.packaging.chunking.maxWords / 1000)}k words/part`);
			break;
		case "maxTokens":
			parts.push(`≤${Math.round(profile.packaging.chunking.maxTokens / 1000)}k tokens/part`);
			break;
		case "maxChars":
			parts.push(`≤${Math.round(profile.packaging.chunking.maxChars / 1000)}k chars/part`);
			break;
	}
	parts.push(profile.packaging.format);
	if (profile.condensation.summarize.enabled) parts.push("summaries");
	if (profile.condensation.dedupe.enabled) parts.push("dedupe");
	if (profile.transform.embeds === "transclude") parts.push("transclusions");
	return parts.join(" · ");
}
