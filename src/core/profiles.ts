export interface ProfileRecipe {
	id: string;
	name: string;
	description: string;
	/** Long-form explanation shown in the profile editor. */
	rationale: string;
	build: () => ExportProfile;
}

function baseProfile(overrides: Partial<ExportProfile> & { id: string; name: string; description: string }): ExportProfile {
	return {
		targets: [],
		depth: -1,
		include: ["**/*.md"],
		exclude: [],
		filters: { ...DEFAULT_FILTERS },
		order: { ...DEFAULT_ORDER },
		transform: { ...DEFAULT_TRANSFORM },
		condensation: {
			...DEFAULT_CONDENSATION,
			dedupe: { ...DEFAULT_CONDENSATION.dedupe },
			boilerplate: { ...DEFAULT_CONDENSATION.boilerplate },
			summarize: { ...DEFAULT_CONDENSATION.summarize },
			dropStubs: { ...DEFAULT_CONDENSATION.dropStubs },
		},
		packaging: {
			...DEFAULT_PACKAGING,
			chunking: { ...DEFAULT_PACKAGING.chunking },
		},
		output: { ...DEFAULT_OUTPUT },
		limits: { ...UNLIMITED_LIMITS },
		...overrides,
	};
}

