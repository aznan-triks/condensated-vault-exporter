/**
 * Profiles ("recipes") and their defaults.
 *
 * A profile is the whole configuration of an export: what to read, how to
 * clean it, how much to condense, how to package it and where to write it.
 * Instead of shipping ten unrelated toggles, the plugin ships a handful of
 * opinionated profiles that are known to work well with a specific
 * destination, and lets the user fork them.
 */

